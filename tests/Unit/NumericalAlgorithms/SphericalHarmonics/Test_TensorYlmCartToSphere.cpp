template <typename TensorStructure>
std::string symm_to_string() {
  if constexpr (std::is_same_v<typename TensorStructure::symmetry,
                               Symmetry<1>>) {
    return "a";
  } else if constexpr (std::is_same_v<typename TensorStructure::symmetry,
                                      Symmetry<1, 1>>) {
    return "aa";
  } else if constexpr (std::is_same_v<typename TensorStructure::symmetry,
                                      Symmetry<2, 1>>) {
    return "ab";
  } else if constexpr (std::is_same_v<typename TensorStructure::symmetry,
                                      Symmetry<3, 2, 1>>) {
    return "abc";
  } else if constexpr (std::is_same_v<typename TensorStructure::symmetry,
                                      Symmetry<2, 1, 1>>) {
    return "abb";
  }
  return "";
}

